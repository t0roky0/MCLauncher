let lang = 'ru';
let dict = RU;

export function setLang(l) {
  lang = l === 'en' ? 'en' : 'ru';
  dict = lang === 'en' ? EN : RU;
  document.documentElement.lang = lang;
}

export function getLang() {
  return lang;
}

function pluralIndex(n) {
  if (lang === 'en') return n === 1 ? 0 : 1;
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return 2;
  if (b > 1 && b < 5) return 1;
  if (b === 1) return 0;
  return 2;
}

export function t(key, params = {}) {
  let v = dict[key];
  if (v === undefined) v = EN[key];
  if (v === undefined) return key;
  if (Array.isArray(v)) v = v[pluralIndex(Number(params.n) || 0)];
  return String(v).replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? String(params[k]) : m));
}
